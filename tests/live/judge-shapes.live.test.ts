describe.skipIf(!live)("verdict shapes behind the first eval's misses (live)", () => {
  it("handles each shape without breaking the controls", async () => {
    const llm = createLlm(loadLlmConfig());
    const rows: string[] = [];
    const byShape: Record<string, { right: number; n: number }> = {};
    let right = 0;
    for (const c of cases) {
      const ps = passages(c.passage);
      const raw = await judgeClaim(llm, c.claim, ps);
      const checked = verifyJudgment(raw, ps);
      const final = await reviewVerdict(llm, { claimText: c.claim, citation: null, verified: checked, passages: ps });
      const ok = c.want.includes(final.verdict);
      if (ok) right += 1;
      (byShape[c.shape] ??= { right: 0, n: 0 }).n += 1;
      if (ok) byShape[c.shape]!.right += 1;
      rows.push(
        `${ok ? "ok  " : "DIFF"} ${c.shape.padEnd(10)} ${c.name.padEnd(44)} want ${c.want.join("|").padEnd(18)} judge ${raw.verdict.padEnd(15)} final ${final.verdict}` +
          `${final.downgradedFrom ? " (quote failed)" : ""}`,
      );
    }
    console.log(`${rows.join("\n")}\n${Object.entries(byShape).map(([s, r]) => `${s}: ${r.right}/${r.n}`).join("  ")}\nright ${right}/${cases.length}`);
    // What holds today (24 Nov 2026, flash-lite judge, Hydrogen review): qualifiers, disclaimers and every control.
    expect(byShape.control!.right, "a control moved").toBe(byShape.control!.n);
    expect(byShape.qualifier!.right, "a qualifier case moved").toBe(byShape.qualifier!.n);
    expect(byShape.disclaimer!.right, "a disclaimer case moved").toBe(byShape.disclaimer!.n);
    // KNOWN LIMIT, printed but not asserted: a right main fact with a reversed "although ..." clause comes out
    // Contradicted at the judge (0 of 2 as written), the shape of eval claim E27. A rule and two examples in the judge
    // prompt did not move it (same 13 of 15 with and without), so the prompt was left alone. The cases that mix
    // connectors ("while", "dan") already come out Partly supported without any change.
  }, 400_000);
});
