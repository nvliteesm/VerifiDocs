//   - a right main fact with a reversed side clause ("... although it struggled on long inputs").
// Controls guard against fixing one shape by breaking another. Passages are normalized the way stored chunks are.
import { describe, expect, it } from "vitest";
import { createLlm, loadLlmConfig } from "../../src/lib/llm/adapter";
